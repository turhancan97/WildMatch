#!/usr/bin/env bash
# Regenerate the pinned pip/conda requirement files from uv.lock (run after `uv lock`).
# uv is the primary route; these files exist so that pip and conda users get the same pins.
set -euo pipefail
cd "$(dirname "$0")/.."
for build in cpu cu126; do
  {
    echo "# Generated by requirements/export.sh from uv.lock; do not edit by hand."
    echo "--extra-index-url https://download.pytorch.org/whl/${build}"
    uv export --frozen --extra "${build}" --extra matchers --extra train --no-hashes --no-dev --no-header
  } > "requirements/${build}.txt"
done

# The Hugging Face Space (space/): the evaluation pins (matchers extra, no train extra, no project), with
# torch/torchvision as plain 2.8.0 / 0.23.0 pins: ZeroGPU accepts only plain supported versions (it rejected
# `+cu128`, 2026-10-10), and the PyPI Linux wheels of 2.8.0 are the CUDA 12.8 build, which has kernels for
# ZeroGPU's Blackwell GPUs (the cu126 build has none). The NVIDIA wheels are left to pip so they match it.
# Git-only packages go to space/no_deps.txt instead, which space/app.py installs with --no-deps at start-up:
# pip cannot reconcile glue-factory's unpinned LightGlue URL with the pinned commit (the Space build failed on
# it), and with dependencies it would add vismatch's `uniception` (suppressed by uv) and SAM 3's numpy<2 pin
# (SAM 3 runs on numpy 2). Their dependencies are all pinned in requirements.txt. SAM 3's own imports (iopath,
# ftfy, decord) are added here. Gradio comes from the Space's sdk_version.
SAM3="sam3 @ git+https://github.com/facebookresearch/sam3.git@f6e51f59500a87c576c2df2323ce56b9fd7a12de"
space_pins=$(uv export --frozen --extra cu126 --extra matchers --no-hashes --no-dev --no-header --no-emit-project \
  | grep -v '^ *#' | grep -vE '^(nvidia-|uniception|wadler-lindig)' \
  | sed -E 's/^(torch|torchvision)==([0-9.]+)\+cu126/\1==\2/')
{
  echo "# Generated by requirements/export.sh from uv.lock; do not edit by hand."
  echo "$space_pins" | grep -v ' @ git+'
  printf '%s\n' "iopath==0.1.10" "ftfy==6.1.1" "portalocker==4.4.0" "wcwidth==0.9.2" "decord==0.6.0"
} > space/requirements.txt
{
  echo "# Generated by requirements/export.sh; installed with --no-deps by app.py (see requirements/export.sh)."
  echo "$space_pins" | grep ' @ git+' | sed 's/ *;.*//'
  echo "$SAM3"
} > space/no_deps.txt
